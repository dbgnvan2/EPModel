"""T-253's seed-block probe: is a verdict that moved across p 0.05 at revision 62 noise at the threshold or an effect?

Purpose: run one criterion on a fixed block of keyed seeds of one engine checkout (``run``), and summarise the blocks
         of several engines (``summarise``): each block's verdict statistic, the spread across blocks, and the paired
         per-seed difference between two engines on the same seeds. A measurement, never a verdict.
Spec:    docs/bowen_agent_model_spec_v2.md#M17.A.1, #M11.4e, #M3.D.4a; learnings P23
Tests:   none; a diagnostic for T-253, reported in docs/review/2026-11-15_t253_seed_blocks.md. Outside the engine hash:
         it changes nothing a run computes. ``run`` calls the record's own ``run_criterion`` with the criterion's seed
         count fixed (``seeds=N``) and ``first_seed`` moved, so block 0 is the record's own seeds.

    python3 tools/t253_seed_blocks.py run REPO CRITERION FIRST_SEED N WORKERS OUT.json   # REPO: an engine checkout
    python3 tools/t253_seed_blocks.py extract OUT_DIR > docs/review/t253_seed_blocks.json
    python3 tools/t253_seed_blocks.py summarise docs/review/t253_seed_blocks.json > docs/review/2026-11-15_t253_seed_blocks.md

``run`` output files are named ``<tag>_<engine>_<first_seed>.json``; ``extract`` keeps the tested readout's per-seed
values of both arms, and ``summarise`` renders from that file alone.
"""

from __future__ import annotations

import dataclasses
import json
import math
import os
import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
TESTED = {"c7": ("M11.C.7[joint over one spouse]", "deviation_fall", +1), "c10": ("M11.C.10", "cut_off_tie_weeks", +1)}
MARGIN = 0.1  # ensemble_margin (config/bowen), as the runner applies it: the margin is this times the baseline sd
ALPHA = 0.05  # ensemble_alpha


def run(repo: str, cid: str, first: int, n: int, workers: int, out: str) -> None:
    sys.path.insert(0, repo)
    os.chdir(repo)
    from src.bowen.ensemble import runner
    from src.bowen.ensemble.criteria_d import CRITERIA_D
    from src.bowen.ensemble.criteria_d2 import CRITERIA_D2
    from src.bowen.io.load import load_constants
    crit = dataclasses.replace({**CRITERIA_D, **CRITERIA_D2}[cid], seeds=n)
    c = load_constants()
    rules = {k: c[k] for k in ("ensemble_block", "ensemble_cap", "ensemble_precision", "ensemble_margin",
                               "ensemble_alpha", "fallback_flag_rate", "equivalence_margin")}
    captured = {}
    verdict_of = runner._verdict

    def keep(criterion, results, converged, rules):
        captured["rows"] = [(s, b.readouts, t.readouts) for s, b, t in results]
        return verdict_of(criterion, results, converged, rules)

    runner._verdict = keep
    started = time.time()
    v = runner.run_criterion(crit, rules, workers=workers, first_seed=first)
    Path(out).write_text(json.dumps({"repo": repo, "criterion": cid, "first_seed": first, "n": n,
                                     "seconds": time.time() - started, "outcome": v.outcome, "readouts": v.readouts,
                                     "per_seed": captured["rows"]}))


def extract(out_dir: str) -> dict:
    data: dict = {}
    for path in sorted(Path(out_dir).glob("*.json")):
        tag, engine, first = path.stem.split("_")
        cid, name, _ = TESTED[tag]
        raw = json.loads(path.read_text())
        assert raw["criterion"] == cid, path
        block = data.setdefault(tag, {}).setdefault(engine, {})
        block[first] = {"outcome": raw["outcome"], "seeds": [s for s, _, _ in raw["per_seed"]],
                        "base": [b[name] for _, b, _ in raw["per_seed"]],
                        "treat": [t[name] for _, _, t in raw["per_seed"]]}
    return data


def _stats(base, treat, direction):
    import numpy as np
    sys.path.insert(0, str(REPO))
    from src.bowen.ensemble.stats import signed_rank
    base, treat = np.array(base, float), np.array(treat, float)
    diff = treat - base
    sd = float(np.std(base, ddof=1)) or float(np.std(diff, ddof=1))
    _, _, p = signed_rank(direction * diff, margin=MARGIN * sd)
    return float(np.mean(diff)), 1.96 * float(np.std(diff, ddof=1)) / math.sqrt(len(diff)), p


def summarise(data: dict) -> str:
    import numpy as np
    out = ["# T-253: seed blocks for two verdicts that crossed p 0.05 at revision 62", "",
           "Generated by `tools/t253_seed_blocks.py summarise docs/review/t253_seed_blocks.json`; do not edit. Run on "
           "Mac Mini1 on 2026-11-15. Engines: `r61` is revision 61 (`d7fba85`) and `r62` revision 62 (`065d3a6`). No "
           "revision-62 effect was found, so the revert of T-247 alone (T-253's step 2) was not run. Block 0 is the "
           "record's own seeds; the others are fresh, disjoint keyed seeds. Each block has "
           "the record's seed count, fixed. p is the record's one-sided signed-rank p with its margin (one tested "
           "readout, so Holm changes nothing). A measurement, not a verdict.", ""]
    for tag, engines in data.items():
        cid, name, direction = TESTED[tag]
        out += [f"## `{cid}` — `{name}`", "", "| Block | Engine | Seeds | Difference ± half-width | p | p < 0.05 |",
                "|---|---|---|---|---|---|"]
        for first in sorted(next(iter(engines.values())), key=int):
            for engine in sorted(engines):
                b = engines[engine].get(first)
                if b:
                    m, h, p = _stats(b["base"], b["treat"], direction)
                    out.append(f"| {first} | {engine} | {len(b['base'])} | {m:+.4g} ± {h:.2g} | {p:.3g} | "
                               f"{'yes' if p < ALPHA else 'no'} |")
        out += ["", "Pooled over the fresh blocks (block 0 left out):", "",
                "| Engine | Seeds | Difference ± half-width | p | Sd of the block means |", "|---|---|---|---|---|"]
        for engine in sorted(engines):
            fresh = [b for f, b in engines[engine].items() if f != "0"]
            if not fresh:
                continue
            m, h, p = _stats(sum((b["base"] for b in fresh), []), sum((b["treat"] for b in fresh), []), direction)
            block_means = [float(np.mean(np.array(b["treat"]) - np.array(b["base"]))) for b in fresh]
            spread = float(np.std(block_means, ddof=1)) if len(block_means) > 1 else float("nan")
            out.append(f"| {engine} | {sum(len(b['base']) for b in fresh)} | {m:+.4g} ± {h:.2g} | {p:.3g} | "
                       f"{spread:.3g} |")
        if "r61" in engines:
            out += ["", "Paired against revision 61 on the same seeds (engine's per-seed difference less r61's):", "",
                    "| Block | Engine | Change of the difference ± half-width | Seeds whose difference changed |",
                    "|---|---|---|---|"]
            for engine in sorted(e for e in engines if e != "r61"):
                pooled = []
                for first in sorted(engines[engine], key=int):
                    a, b = engines["r61"].get(first), engines[engine][first]
                    if not a:
                        continue
                    assert a["seeds"] == b["seeds"]
                    d = (np.array(b["treat"]) - np.array(b["base"])) - (np.array(a["treat"]) - np.array(a["base"]))
                    if first != "0":
                        pooled += list(d)
                    out.append(f"| {first} | {engine} | {np.mean(d):+.4g} ± {1.96 * np.std(d, ddof=1) / math.sqrt(len(d)):.2g} "
                               f"| {int(np.sum(d != 0))} of {len(d)} |")
                if pooled:
                    d = np.array(pooled)
                    out.append(f"| fresh pooled | {engine} | {np.mean(d):+.4g} ± "
                               f"{1.96 * np.std(d, ddof=1) / math.sqrt(len(d)):.2g} | {int(np.sum(d != 0))} of {len(d)} |")
        out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    mode = sys.argv[1]
    if mode == "run":
        run(sys.argv[2], sys.argv[3], int(sys.argv[4]), int(sys.argv[5]), int(sys.argv[6]), sys.argv[7])
    elif mode == "extract":
        print(json.dumps(extract(sys.argv[2])))
    elif mode == "summarise":
        print(summarise(json.loads(Path(sys.argv[2]).read_text())))
