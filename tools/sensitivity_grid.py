"""A two-constant sensitivity grid (T-236, from T-230): each criterion run at every point of a grid over two `[I]`
constants, the rest at their central values. A measurement, never a verdict: no constant moves by it (`M10.B.4`) and
no criterion's verdict or disposition changes.

Purpose: T-230 found that `DISTANCE` relieves more at once than `TRIANGLE` inside the run's horizon, so triangling is
         not learned (`M11.C.42`, `C.44`, `C.45` fail at the central constants). The grid shows whether those verdicts
         turn as `distance_binding_rate` falls and `triangle_transfer_rate` rises. Each point is a ``Mutant`` of
         ``config/bowen/constants.md`` run in a temporary copy (``tools/mutant_runner.py``) and cached by the engine
         hash and its edits (``tools/record_cache.py``), so this file is outside the engine hash and can change
         without rerunning anything. The central point is the unmodified model. Each point's verdict is the runner's
         at its adaptive stop; the sweep's detection-limit rerun (`M17.A.1`) is not applied.
Spec:    docs/bowen_agent_model_spec_v2.md#M17.E.1 (the sweep this borrows from), #M10.B.4
Tests:   tests/test_sensitivity_grid.py

    python3 tools/sensitivity_grid.py [--workers N | --render-only]
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from tools.record_cache import ERRORED, Cache, engine_hash, exit_status, result_key, run_cached  # noqa: E402
from tools.sweep_config import central_values  # noqa: E402
from tools.version_2_sweep import central_verdicts, format_value, sample_mutant  # noqa: E402

RECORD = REPO / "docs" / "sensitivity_distance_triangle.md"
CACHE_NAME = "sensitivity_grid"
CRITERIA = ("M11.C.42", "M11.C.44", "M11.C.45")
ROW, COLUMN = "distance_binding_rate", "triangle_transfer_rate"
# Near log-spaced over the sweep's declared range for both constants (0.15 to 0.6, `config/sweep/sweep.md`), the
# central value 0.3 in the middle. Odd indices first, so the 3 x 3 corners and centre run before the fill.
VALUES = (0.15, 0.21, 0.3, 0.42, 0.6)


def points() -> list[tuple[float, float]]:
    coarse = [v for i, v in enumerate(VALUES) if i % 2 == 0]
    first = [(r, c) for r in coarse for c in coarse]
    return first + [(r, c) for r in VALUES for c in VALUES if (r, c) not in first]


def mutant_at(point: tuple[float, float], central: dict[str, str]):
    """None at the central values (the unmodified model), else the point as a mutant of both rows."""
    sample = {ROW: point[0], COLUMN: point[1]}
    if all(format_value(v) == central[k] for k, v in sample.items()):
        return None
    return sample_mutant("T-236 grid", points().index(point), sample, central)


def results(cache: Cache, workers: int | None) -> dict[tuple[float, float], dict[str, dict]]:
    """Every point's three results. With ``workers``, missing ones are run; without, a missing one raises ``KeyError``."""
    central, engine, out = central_values(), engine_hash(), {}
    for point in points():
        mutant = mutant_at(point, central)
        if workers is not None:
            rows = run_cached(cache, mutant, list(CRITERIA), workers, label=f"{ROW}={point[0]} {COLUMN}={point[1]}")
        else:
            definition = mutant.definition() if mutant else None
            rows = [cache.get(result_key(engine, definition, cid)) for cid in CRITERIA]
            if any(r is None for r in rows):
                raise KeyError(f"{point}: no cached result for the current engine")
        out[point] = dict(zip(CRITERIA, rows))
    return out


def cell(row: dict) -> str:
    if row["outcome"] in ERRORED:
        return f"{row['outcome']}"
    gating = [r for r in row.get("readouts", ()) if not r.get("report_only") and r.get("direction")]
    text = row["outcome"] if row["outcome"] != "UNDETERMINED" else "UND"
    if gating:
        r = gating[0]
        text += f" {r['mean_difference']:+.3g} ± {r['half_width']:.2g}"
    return f"{text} ({row['seeds']})"


def render(grid: dict, engine: str, numpy_version: str) -> str:
    centrals = central_verdicts()
    lines = [
        "# Sensitivity: `distance_binding_rate` against `triangle_transfer_rate` (T-236)",
        "",
        f"Generated by `tools/sensitivity_grid.py` from `records_cache/{CACHE_NAME}.json`; engine `{engine}`, NumPy "
        f"{numpy_version}. Do not edit by hand.",
        "",
        "A sensitivity result, report only (T-230): no constant moves by it (`M10.B.4`) and no verdict or disposition "
        "changes. Each criterion is run at every point of the grid, every other constant at its central value. A cell "
        "is the runner's verdict at its adaptive stop, the first gating readout's mean difference ± half-width, and "
        "the seeds taken; the detection-limit rerun (`M17.A.1`) is not applied. The central point (0.3, 0.3) is the "
        "unmodified model.",
        "",
    ]
    for cid in CRITERIA:
        rows = [grid[p][cid] for p in points()]
        held = sum(1 for r in rows if r["outcome"] == "PASS")
        errored = sum(1 for r in rows if r["outcome"] in ERRORED)
        gating = [r["readout"] for r in rows[0].get("readouts", ()) if not r.get("report_only") and r.get("direction")]
        lines += [f"## `{cid}`", "",
                  f"PASS at {held} of {len(rows) - errored} points ({errored} errored). The central record's verdict: "
                  f"{centrals[cid]['outcome']}. Gating readout: `{gating[0] if gating else '—'}`.", "",
                  f"| `{ROW}` \\ `{COLUMN}` | " + " | ".join(format_value(c) for c in VALUES) + " |",
                  "|---|" + "---|" * len(VALUES)]
        for r in VALUES:
            lines.append(f"| {format_value(r)} | " + " | ".join(cell(grid[(r, c)][cid]) for c in VALUES) + " |")
        lines.append("")
    return "\n".join(lines)


def build(cache: Cache, workers: int | None = None) -> str:
    grid = results(cache, workers)
    if workers is not None:
        cache.meta["numpy"] = np.__version__
    return render(grid, engine_hash(), cache.meta.get("numpy", "unrecorded"))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--workers", type=int, default=os.cpu_count() or 1)
    parser.add_argument("--render-only", action="store_true", help="render from the cache; run nothing")
    args = parser.parse_args(argv)
    cache = Cache(CACHE_NAME)
    text = build(cache, None if args.render_only else args.workers)
    cache.save()
    RECORD.write_text(text + "\n", encoding="utf-8")
    print(f"wrote {RECORD.relative_to(REPO)}")
    return exit_status()


if __name__ == "__main__":
    raise SystemExit(main())
