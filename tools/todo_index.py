"""Generate TODO.md, the closed-items region of docs/TODO_archive.md and the entry index of CHANGELOG.md.

Purpose: a session reads one line per open item instead of its reasoning (owner rule, 2026-10-22: read by index, not
         by file). The reasoning lives in the records under docs/todo/, one file per batch; this tool reads them and
         never writes them. Ticking an item in its record and running the tool moves its line from TODO.md to the
         archive. The changelog index is one line per `### ` entry, so a session greps the index and opens one entry.
Spec:    CLAUDE.md — "Token budget — how to read this repo"; docs/plan_model_ergonomics.md
Tests:   tests/test_todo_index.py

    python3 tools/todo_index.py

A record is docs/todo/<YYYY-MM-DD>_<slug>.md. An item in it is one line `- [ ] T-nnn ⟨now⟩ text` or
`- [x] T-nnn ⟨later⟩ text`, continued on indented lines; its ID is unique across the records and it carries exactly
one of the two tags. The item's date is the first ISO date in its text, else the record's date; a ticked item's
close date is the latest ISO date in its text, else the record's date. Its title is its leading bold span, else its
first line, cut to ``TITLE_WORDS`` words. Everything else in a record (its heading, notes, sub-headings) is for a
reader of the record and is not indexed.
"""

from __future__ import annotations

import re
import sys
from dataclasses import dataclass
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
RECORDS = "docs/todo"
TODO = "TODO.md"
ARCHIVE = "docs/TODO_archive.md"
CHANGELOG = "CHANGELOG.md"
ARCHIVE_BEGIN = "<!-- todo_index: closed items begin (generated by tools/todo_index.py from docs/todo/; do not edit) -->"
ARCHIVE_END = "<!-- todo_index: closed items end -->"
CHANGELOG_BEGIN = "<!-- changelog index begin (generated by tools/todo_index.py; do not edit) -->"
CHANGELOG_END = "<!-- changelog index end -->"
TAGS = ("now", "later")
TITLE_WORDS = 8

_FILE = re.compile(r"^(\d{4}-\d{2}-\d{2})_[a-z0-9_]+\.md$")
_ITEM = re.compile(r"^- \[([ xX])\] (.*)$")
_ID_TAGS = re.compile(r"^(T-\d{3}) ((?:⟨[a-z]+⟩ )*)(.*)$")
_ISO = re.compile(r"\b(20\d\d-\d\d-\d\d)\b")
_ENTRY = re.compile(r"^### (.*)$")
_SECTION = re.compile(r"^## (.*)$")


@dataclass(frozen=True)
class Item:
    id: str
    tag: str
    closed: bool
    text: str        # the item's text after its box, ID and tag, continuation lines included
    record: str      # repo-relative path of its record
    line: int        # 1-based line of its box in the record
    record_date: str


def parse_record(record: str, text: str) -> tuple[list[Item], list[str]]:
    """The items of one record and the problems found: an item without an ID, or without exactly one tag."""
    name = record.rsplit("/", 1)[-1]
    match = _FILE.match(name)
    problems = [] if match else [f"{record}: the file name is not <YYYY-MM-DD>_<slug>.md"]
    record_date = match.group(1) if match else ""
    lines = text.split("\n")
    items: list[Item] = []
    i = 0
    while i < len(lines):
        box = _ITEM.match(lines[i])
        if not box:
            i += 1
            continue
        j = i + 1
        while j < len(lines) and lines[j].startswith(" "):
            j += 1
        head = _ID_TAGS.match(box.group(2))
        if not head:
            problems.append(f"{record}:{i + 1}: item without an ID (`- [ ] T-nnn ⟨now⟩ …`)")
        else:
            tags = re.findall(r"⟨([a-z]+)⟩", head.group(2))
            if len(tags) != 1 or tags[0] not in TAGS:
                problems.append(f"{record}:{i + 1}: {head.group(1)} must carry exactly one of ⟨now⟩ ⟨later⟩, has {tags}")
            else:
                body = "\n".join([head.group(3)] + lines[i + 1:j])
                items.append(Item(head.group(1), tags[0], box.group(1).lower() == "x", body, record, i + 1, record_date))
        i = j
    return items, problems


def records(repo: Path = REPO) -> tuple[list[Item], list[str]]:
    """Every item of every record, in file-name then line order, and every problem, duplicate IDs included."""
    items: list[Item] = []
    problems: list[str] = []
    for path in sorted((repo / RECORDS).glob("*.md")):
        found, bad = parse_record(path.relative_to(repo).as_posix(), path.read_text(encoding="utf-8"))
        items += found
        problems += bad
    seen: dict[str, str] = {}
    for item in items:
        where = f"{item.record}:{item.line}"
        if item.id in seen:
            problems.append(f"{where}: {item.id} is also at {seen[item.id]}")
        seen.setdefault(item.id, where)
    return items, problems


def item_date(item: Item) -> str:
    dates = _ISO.findall(item.text)
    return dates[0] if dates else item.record_date


def closed_date(item: Item) -> str:
    dates = sorted(_ISO.findall(item.text))
    return dates[-1] if dates else item.record_date


def title(text: str) -> str:
    """The leading bold span, else the first line, without strike-through or emphasis marks, cut to TITLE_WORDS."""
    first = text.split("\n", 1)[0].replace("~~", "").strip()
    bold = re.match(r"\*\*(.+?)\*\*", first)
    source = re.sub(r"\*", "", bold.group(1) if bold else first).strip()
    source = re.sub(r"[.:;,]+$", "", source)
    words = source.split()
    if len(words) > TITLE_WORDS:
        source = " ".join(words[:TITLE_WORDS]) + " …"
        if source.count("`") % 2:
            source = source.replace(" …", "` …")
    return source


def _line(item: Item, date: str, base: str) -> str:
    link = item.record[len(base):] if base and item.record.startswith(base) else item.record
    return f"- {item.id} · {date} · {title(item.text)} · [record]({link})"


def render_todo(items: list[Item]) -> str:
    open_items = [i for i in items if not i.closed]
    out = [
        "# TODO",
        "",
        "<!-- generated by tools/todo_index.py from docs/todo/*.md; do not edit: edit the record, then run the tool -->",
        "",
        "Open items, one line each: ID, date raised, title, record. **Now** blocks version 2 stage 2 or the next commit;",
        "**Later** waits for a regeneration, a revision or an owner decision. An item's reasoning is in its record under",
        "`docs/todo/` (grep its ID). To close one, tick it in its record and run `python3 tools/todo_index.py`: its line",
        "moves to `docs/TODO_archive.md`. Until 2026-10-22 this file held every item's text; that form is in git history.",
        "",
    ]
    for tag, heading in (("now", "Now"), ("later", "Later")):
        chosen = sorted((i for i in open_items if i.tag == tag), key=lambda i: i.id)   # IDs follow the old document order
        out += [f"## {heading} ({len(chosen)})", ""]
        out += [_line(i, item_date(i), "") for i in chosen]
        out.append("")
    return "\n".join(out)


def render_closed(items: list[Item]) -> str:
    """The archive's generated region: one line per ticked record item, most recently closed first, then by ID."""
    closed = sorted((i for i in items if i.closed), key=lambda i: (closed_date(i), i.id), reverse=True)
    lines = [_line(i, f"closed {closed_date(i)}", "docs/") for i in closed]
    return "\n".join(lines) if lines else "(none yet)"


def render_changelog_index(changelog: str) -> str:
    """One line per `### ` entry, in order: its date (the first in its heading, else its section's) and its heading."""
    out, section_date = [], ""
    for line in changelog.split("\n"):
        section = _SECTION.match(line)
        if section:
            dates = _ISO.findall(section.group(1))
            section_date = dates[0] if dates else section_date
        entry = _ENTRY.match(line)
        if entry:
            dates = _ISO.findall(entry.group(1))
            out.append(f"- {dates[0] if dates else section_date} — {entry.group(1)}")
    return "\n".join(out) if out else "(no entries)"


def with_region(text: str, begin: str, end: str, body: str) -> str:
    """`text` with the region between the marker lines replaced by `body`; without markers, the region is put before
    the first `## ` heading."""
    lines = text.split("\n")
    if begin in lines and end in lines:
        a, b = lines.index(begin), lines.index(end)
        assert a < b and lines.count(begin) == 1 and lines.count(end) == 1, "the region markers must appear once, in order"
        return "\n".join(lines[:a + 1] + body.split("\n") + lines[b:])
    first = next(i for i, l in enumerate(lines) if l.startswith("## "))
    return "\n".join(lines[:first] + [begin] + body.split("\n") + [end, ""] + lines[first:])


def generate(repo: Path = REPO) -> dict[str, str]:
    """What each of the three files should hold now. Raises on a record problem; writes nothing."""
    items, problems = records(repo)
    if problems:
        raise ValueError("records are not well formed:\n" + "\n".join(problems))
    changelog = (repo / CHANGELOG).read_text(encoding="utf-8")
    archive = (repo / ARCHIVE).read_text(encoding="utf-8")
    return {
        TODO: render_todo(items),
        ARCHIVE: with_region(archive, ARCHIVE_BEGIN, ARCHIVE_END, render_closed(items)),
        CHANGELOG: with_region(changelog, CHANGELOG_BEGIN, CHANGELOG_END, render_changelog_index(changelog)),
    }


def main(argv: list[str], repo: Path = REPO) -> int:
    try:
        texts = generate(repo)
    except ValueError as exc:
        print(exc, file=sys.stderr)
        return 1
    for rel, text in texts.items():
        path = repo / rel
        if path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {rel}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
