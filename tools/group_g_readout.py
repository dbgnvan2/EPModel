"""Measure what group G changes, before and after it is built: the stock a cutoff binds, the negative runs before a
cutoff, and the load on the reference families.

Purpose: the readout G1's order of work puts first (`docs/PROPOSAL — CUTOFF ANXIETY, BRIDGING AND REPAIR.md` §6 step
         1, §3.7, §4) and the Holmes–Rahe proposal's §5: on the two reference families over many seeds, the largest
         `distance_bound_anxiety` a tie holds in the week it becomes cut off (this fixes `cutoff_stock_cap`), the run of
         negative contacts before each tie's first cutoff against the longest run on uncut ties over the same weeks
         (`M11.C.48`'s readout, `src/bowen/readouts/negative_runs.py`), the mean excess anxiety of the living members, and
         the share of person-weeks with an active symptom. It writes one section per label into
         `docs/review/group_g_readout.md` and keeps the other label's section, so "before" (the engine before revision
         36) and "after" stand side by side. Everything here is a measurement; it writes no rule.
Spec:    docs/bowen_agent_model_spec_v2.md#M1.D.2b, #M11.C.48
Tests:   tests/test_group_g_readout.py::test_g1_readout_section_is_rendered_from_measurements,
         tests/test_group_g_readout.py::test_g1_readout_page_keeps_the_other_labels_section,
         tests/test_group_g_readout.py::test_m11c48_t166_readout_leaves_unmatched_first_cutoffs_out_of_the_run_columns_and_counts_them

    python3 tools/group_g_readout.py --label before|after [--seeds 20] [--workers 10]
"""

from __future__ import annotations

import argparse
import datetime as dt
import re
import statistics
import sys
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

OUT = REPO / "docs" / "review" / "group_g_readout.md"
LABELS = ("before", "after")
# The reference runs: the Phase C family under `M11.C.1`'s baseline spell for ten years, and the Phase D family's life
# course for forty, as `M11.C.10` runs it (`config/bowen/criteria.md`).
RUNS = {"phase_c": 520, "phase_d": 52 * 40}
HEADER = """# Group G readout — before and after spec revision 36

Generated by `tools/group_g_readout.py`; do not edit. Each section is one measurement of the engine at the hash it
names, on the reference families (`config/bowen/family_phase_c.md` under `M11.C.1`'s baseline spell for 520 weeks;
`config/bowen/family_phase_d.md`'s life course for 2080 weeks), over the seeds it says. "Stock at the cut" is a tie's
`distance_bound_anxiety` in the week it becomes cut off (the largest fixes `cutoff_stock_cap`, G1 §3.7). "Run before
the first cutoff" and "matched uncut run" are `M11.C.48`'s two arms (`docs/readouts_phase_c.md`, "Negative runs");
"longest uncut run", the span-longest run on the uncut ties, is reported only (a "before" section has only that one).
The run columns read only matched first cutoffs: one with no uncut tie in its week has no baseline, is left out of
them and is counted under "unmatched" (T-123, T-166). The committed "before" section has no "unmatched" column: it was measured
on the earlier definition, which counted such a cutoff with a baseline of 0.
"Excess anxiety" is the mean over living family members and weeks of acute anxiety above the chronic floor. "Symptom
weeks" is the share of living-member weeks with any active symptom channel. A seed with no cutoff is counted in
"seeds with a cutoff" and contributes no run. Not a real family (`M11.F.9`). The "before" section was measured on
the engine before any revision 36 rule, at a hash that differs from version 1's (`91f9a81756a5`, the tag's) only by
the event-kind rows, the contact classes and the loader fields that revision 36 added first and that no rule yet read.
"""


def one_run(args: tuple[str, int]) -> dict:
    family, seed = args
    from src.bowen.engine.objects import Role, TieState
    from src.bowen.ensemble.criteria import scenario, spell
    from src.bowen.io.load import load_event_kinds
    from src.bowen.readouts.negative_runs import first_cutoff_runs

    weeks = RUNS[family]
    cuts: list[tuple[str, int, float, float]] = []
    was: dict = {}
    excess_sum, excess_n, symptom_weeks, member_weeks = 0.0, 0, 0, 0

    def watch(state):
        nonlocal excess_sum, excess_n, symptom_weeks, member_weeks
        for tie_id in sorted(state.ties):
            tie = state.ties[tie_id]
            cut = tie.tie_state is TieState.CUT_OFF
            if cut and not was.get(tie_id, False):
                cuts.append((str(tie_id), state.tick, tie.distance_bound_anxiety, tie.bond_energy))
            was[tie_id] = cut
        for p in state.people.values():
            if p.alive and p.role is Role.MEMBER:
                excess_sum += max(0.0, p.acute_anxiety - p.chronic_anxiety)
                excess_n += 1
                member_weeks += 1
                symptom_weeks += int(any(p.symptom_active.values()))

    declared: set = set()

    def setup(state):  # the ties the family declares cut off have no first cutoff in the run
        declared.update(t for t, tie in state.ties.items() if tie.tie_state is TieState.CUT_OFF)
        for t in declared:
            was[t] = True

    spells = spell("phase_c", weeks) if family == "phase_c" else ()
    state, records = scenario(family, seed, weeks, spells=spells, setup=setup, watch=watch)
    members = frozenset(p for p, q in state.people.items() if q.role is Role.MEMBER)
    firsts = first_cutoff_runs(records, load_event_kinds(), members, frozenset(declared))
    return {
        "family": family, "seed": seed, "cuts": cuts,
        "firsts": [(str(f.tie), f.week, f.run, f.uncut, f.longest_uncut, f.matched) for f in firsts],
        "excess": excess_sum / excess_n if excess_n else 0.0,
        "symptom_share": symptom_weeks / member_weeks if member_weeks else 0.0,
    }


def measure(seeds: int, workers: int) -> list[dict]:
    jobs = [(family, seed) for family in RUNS for seed in range(1, seeds + 1)]
    if workers <= 1:
        return [one_run(j) for j in jobs]
    with ProcessPoolExecutor(max_workers=workers) as pool:
        return list(pool.map(one_run, jobs))


def _fmt(x: float) -> str:
    return f"{x:.4g}"


def render_section(label: str, results: list[dict], engine: str, seeds: int) -> str:
    lines = [f"## {label} — engine hash `{engine[:12]}`, {seeds} seeds per family, {dt.date.today().isoformat()}", ""]
    lines.append("| family | weeks | cuts | largest stock at a cut (tie, week, seed) | median stock at a cut | "
                 "seeds with a cutoff | first cutoffs | unmatched | mean run before the first cutoff | median run | "
                 "mean matched uncut run | mean longest uncut run | excess anxiety | symptom weeks |")
    lines.append("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for family in RUNS:
        rows = [r for r in results if r["family"] == family]
        cuts = [(c, r["seed"]) for r in rows for c in r["cuts"]]
        firsts = [f for r in rows for f in r["firsts"]]
        stocks = [c[2] for c, _ in cuts]
        if cuts:
            (tie, week, stock, bond), seed = max(cuts, key=lambda cs: cs[0][2])
            largest = f"{_fmt(stock)} (`{tie}`, week {week}, seed {seed}, bond {_fmt(bond)})"
        else:
            largest = "no cut"
        kept = [f for f in firsts if f[5]]  # matched only: an unmatched first cutoff has no baseline (T-123, T-166)
        runs = [f[2] for f in kept]
        matched = [f[3] for f in kept]
        best = [f[4] for f in kept]
        lines.append("| {} | {} | {} | {} | {} | {} of {} | {} | {} | {} | {} | {} | {} | {} | {} |".format(
            family, RUNS[family], len(cuts), largest, _fmt(statistics.median(stocks)) if stocks else "—",
            sum(1 for r in rows if r["firsts"]), len(rows), len(firsts), len(firsts) - len(kept),
            _fmt(statistics.mean(runs)) if runs else "—", _fmt(statistics.median(runs)) if runs else "—",
            _fmt(statistics.mean(matched)) if matched else "—", _fmt(statistics.mean(best)) if best else "—",
            _fmt(statistics.mean(r["excess"] for r in rows)), _fmt(statistics.mean(r["symptom_share"] for r in rows))))
    lines.append("")
    lines.append(f"<!-- {label} measurements: " + repr({
        "engine": engine, "seeds": seeds,
        "largest_stock": {f: max((c[2] for r in results if r["family"] == f for c in r["cuts"]), default=0.0) for f in RUNS},
        "mean_run": {f: (statistics.mean([x[2] for r in results if r["family"] == f for x in r["firsts"] if x[5]])
                         if any(x[5] for r in results if r["family"] == f for x in r["firsts"]) else None)
                     for f in RUNS},
        "unmatched": {f: sum(1 for r in results if r["family"] == f for x in r["firsts"] if not x[5]) for f in RUNS},
        "excess": {f: statistics.mean(r["excess"] for r in results if r["family"] == f) for f in RUNS},
        "symptom_share": {f: statistics.mean(r["symptom_share"] for r in results if r["family"] == f) for f in RUNS},
    }) + " -->")
    lines.append("")
    return "\n".join(lines)


def sections(text: str) -> dict[str, str]:
    """The labelled sections of the committed page, by label."""
    found = {}
    for m in re.finditer(r"^## (before|after) — .*?(?=^## (?:before|after) — |\Z)", text, re.M | re.S):
        found[m.group(1)] = m.group(0).rstrip("\n") + "\n"
    return found


def render_page(new_label: str, new_section: str, existing: str) -> str:
    kept = sections(existing)
    kept[new_label] = new_section
    return HEADER + "\n" + "\n".join(kept[label] for label in LABELS if label in kept)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--label", choices=LABELS, required=True)
    parser.add_argument("--seeds", type=int, default=20)
    parser.add_argument("--workers", type=int, default=10)
    args = parser.parse_args()
    from tools.record_cache import engine_hash

    engine = engine_hash()
    results = measure(args.seeds, args.workers)
    section = render_section(args.label, results, engine, args.seeds)
    existing = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    OUT.write_text(render_page(args.label, section, existing), encoding="utf-8")
    print(section)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
