"""Generate docs/STATUS.md: where the project stands, read from the files that hold each fact.

Purpose: the spec's revision, the requirement count, the engine hash and version 2's conditions were restated by hand
         in seven documents, and the copies disagreed (the whole-repo review of 2026-11-11, D3, D4; T-225). This tool
         reads each fact from its source and writes one page; every other document says where things stand in one
         sentence and points here. History stays in docs/spec_revision_log.md and CHANGELOG.md.
Spec:    docs/todo/2026-11-11_whole_repo_review.md (T-225)
Tests:   tests/test_status.py

    python3 tools/status.py
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "docs" / "STATUS.md"
SPEC = REPO / "docs" / "bowen_agent_model_spec_v2.md"
INDEX = REPO / "docs" / "spec_index.jsonl"
LOG = REPO / "docs" / "spec_revision_log.md"
HASH_SOURCE = REPO / "docs" / "phase_c_mutation_record.md"
VERSION_2 = REPO / "docs" / "version_2_status.md"
HASH_LINE = re.compile(r"^engine_hash: ([0-9a-f]{12})", re.M)


def _one(pattern: str, text: str, where: Path, flags: int = re.M) -> re.Match:
    found = re.search(pattern, text, flags)
    if not found:
        raise SystemExit(f"{where.relative_to(REPO)}: no line matches {pattern!r}")
    return found


def facts() -> dict:
    spec = SPEC.read_text(encoding="utf-8")
    rows = [json.loads(line) for line in INDEX.read_text(encoding="utf-8").splitlines() if line.strip()]
    latest = _one(r"^### (Revision \d+ — .*?)(?: ⟦.*)?$", LOG.read_text(encoding="utf-8"), LOG).group(1)
    return {
        "revision": _one(r"^version: (.+)$", spec, SPEC).group(1),
        "requirements": len(rows),
        "withdrawn": sum(1 for r in rows if r["withdrawn"]),
        "latest": latest,
        "engine": _one(HASH_LINE.pattern, HASH_SOURCE.read_text(encoding="utf-8"), HASH_SOURCE).group(1),
        "conditions": re.findall(r"^- (W\d .*)$", VERSION_2.read_text(encoding="utf-8"), re.M),
    }


def render(f: dict) -> str:
    lines = [
        "# Project status",
        "",
        "Generated by `tools/status.py` from the files each line names; do not edit. History is in",
        "`docs/spec_revision_log.md` (every spec revision) and `CHANGELOG.md` (every batch).",
        "",
        f"- **Spec:** `docs/bowen_agent_model_spec_v2.md`, version {f['revision']} (its `version:` line); "
        f"{f['requirements']} numbered requirements, {f['withdrawn']} of them withdrawn (`docs/spec_index.jsonl`).",
        f"- **Latest revision:** {f['latest']} (`docs/spec_revision_log.md`).",
        f"- **Engine hash:** `{f['engine']}` (`docs/phase_c_mutation_record.md`'s `engine_hash`).",
        "- **Open items:** `TODO.md`, one line each.",
        "",
        "## Version 2's conditions (`docs/version_2_status.md`)",
        "",
        *[f"- {c}" for c in f["conditions"]],
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    OUT.write_text(render(facts()), encoding="utf-8")
    print(f"written: {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
