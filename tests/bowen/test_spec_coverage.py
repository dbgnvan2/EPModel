def _unjudged(note: str) -> bool:
    """A4's note on a module a built phase builds, in whole ("its module was built in Phase C") or in part ("Phase C,
    D or E builds it; Phase E is not built yet"). A module no built phase builds, and a rule checked in every phase
    ("no test named for it (every phase)"), are not Part B's to judge."""
    return note.startswith("no test named for it;") and "builds it and is not built yet" not in note


def test_m141_no_built_id_is_left_without_a_judgment():
    """Plan B1.1 (docs/plan_spec_coverage_phase_d.md §6): every ID in a module a built phase builds carries a
    judgment — a test named for it, a record, or an override that says which test verifies it, that it is built with
    no test, or why it is not done — so no row is left reading only that its module was built. A new ID added to a
    built module without its test fails here until it is judged. Mutation: delete one Part B override."""
    assert _unjudged(TOOL.untested_note("C", "")), "A4's wording changed; this checks nothing"
    assert _unjudged(TOOL.untested_note("C, D or E", "M11.E")), "a partly built module is read as unbuilt"
    assert not _unjudged(TOOL.untested_note("E", "")) and not _unjudged(TOOL.untested_note("", "every phase"))
    left = [r["id"] for r in _rows().values() if _unjudged(r["note"])]
    assert left == [], f"built, with no test named for it and no judgment: {left}"


