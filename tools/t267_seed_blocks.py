def mutate(repo: str, mutant_id: str, dest: str) -> None:
    sys.path.insert(0, repo)
    os.chdir(repo)
    for name in [n for n in sys.modules if n == "tools" or n.startswith("tools.")]:
        del sys.modules[name]  # the mutant is the engine's own: import its checkout's tools, not this file's
    from tools.mutant_runner import apply
    from tools.mutation_record import MUTANTS as PHASE_C
    from tools.phase_d_mutation_record import MUTANTS as PHASE_D
    from tools.sweep_record import SETTINGS, row_mutant
    if "=" in mutant_id:  # a sweep setting, made as the sweep record makes it: one constant's edit in constants.md
        name, value = mutant_id.split("=")
        mutant = row_mutant(name, next(c for n, c, _, _ in SETTINGS if n == name), value)
    else:
        mutant = next(m for m in (*PHASE_C, *PHASE_D) if m.id == mutant_id)
    Path(dest).mkdir(parents=True)
    for part in ("src", "config", "tools"):
        shutil.copytree(Path(repo) / part, Path(dest) / part, ignore=shutil.ignore_patterns("__pycache__"))
    apply(Path(dest), mutant)


if __name__ == "__main__":
    mode = sys.argv[1]
    if mode == "mutate":
        mutate(sys.argv[2], sys.argv[3], sys.argv[4])
    elif mode == "run":
        base.run(sys.argv[2], sys.argv[3], int(sys.argv[4]), int(sys.argv[5]), int(sys.argv[6]), sys.argv[7])
    elif mode == "extract":
        print(json.dumps(base.extract(sys.argv[2])))
    elif mode == "summarise":
        print(base.summarise(json.loads(Path(sys.argv[2]).read_text()), HEADER))
