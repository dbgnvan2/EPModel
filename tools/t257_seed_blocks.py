"""T-257's seed blocks: is abort the usual first outcome of an I-POSITION sequence (`M5.D.3`) on fresh seeds?

Purpose: ``test_m5d3_abort_is_the_usual_first_outcome`` counts what each opposition led to first, abort or hold, over
         the triad's seeds 0-191. This file runs the same fixture (the test's own ``attempt_marks`` and
         ``first_outcomes``, imported, not copied) on fresh blocks of the test's size and counts abort and hold per
         block and pooled, with an exact binomial test on the pooled counts. A measurement, never a verdict.
Spec:    docs/bowen_agent_model_spec_v2.md#M5.D.3; learnings P23
Tests:   none; a diagnostic for T-257, reported in docs/review/2026-11-23_t257_seed_blocks.md. Outside the engine hash:
         it changes nothing a run computes.

    python3 tools/t257_seed_blocks.py run REPO FIRST_SEED N WORKERS OUT.json      # REPO: an engine checkout
    python3 tools/t257_seed_blocks.py extract OUT_DIR > docs/review/t257_seed_blocks.json
    python3 tools/t257_seed_blocks.py summarise docs/review/t257_seed_blocks.json > docs/review/2026-11-23_t257_seed_blocks.md
"""

from __future__ import annotations

import json
import os
import sys
import time
from concurrent.futures import ProcessPoolExecutor
from math import comb
from pathlib import Path

IN_SUITE = 0  # the first seed of the test's own block; reported, never pooled

HEADER = ["# T-257: seed blocks for `M5.D.3`'s abort-before-hold claim", "",
          "Generated by `tools/t257_seed_blocks.py summarise docs/review/t257_seed_blocks.json`; do not edit. Run on "
          "Mac Mini1 on 2026-11-23 on revision 67 (engine hash `9321b8523500`). The fixture is "
          "`test_m5d3_abort_is_the_usual_first_outcome`'s: the triad, F at level 60 with full perspective taking "
          "I-POSITION toward M, 100 weeks a seed. Each opposition counts once, by what it led to first: abort or "
          "hold. Seed 0's block is the test's own and is not pooled; the fresh blocks are disjoint from it and from "
          "T-253, T-264 and T-267's blocks (first seed 40000 to 47000). The binomial p is exact, on the pooled fresh "
          "counts against an even split: one-sided for abort above hold, and two-sided. A measurement, not a "
          "verdict; its reading is in T-257's record.", ""]


def _module(repo: str):
    sys.path.insert(0, repo)
    sys.path.insert(0, str(Path(repo) / "tests" / "bowen"))
    os.chdir(repo)
    import test_iposition
    return test_iposition


def _one(job):
    repo, seed = job
    t = _module(repo)
    return seed, t.first_outcomes([t.attempt_marks(seed)])


def run(repo: str, first: int, n: int, workers: int, out: str) -> None:
    started = time.time()
    with ProcessPoolExecutor(max_workers=workers) as pool:
        rows = sorted(pool.map(_one, [(repo, s) for s in range(first, first + n)]))
    Path(out).write_text(json.dumps({"repo": repo, "first_seed": first, "n": n, "seconds": time.time() - started,
                                     "per_seed": [[s, a, h] for s, (a, h) in rows]}))


def extract(out_dir: str) -> dict:
    blocks = [json.loads(p.read_text()) for p in sorted(Path(out_dir).glob("*.json"))]
    return {"blocks": [{"first_seed": b["first_seed"], "n": b["n"], "per_seed": b["per_seed"]}
                       for b in sorted(blocks, key=lambda b: b["first_seed"])]}


def binomial_p(k: int, n: int) -> tuple[float, float]:
    """(one-sided P(X >= k), two-sided) for X ~ Binomial(n, 1/2)."""
    upper = sum(comb(n, i) for i in range(k, n + 1)) / 2 ** n
    lower = sum(comb(n, i) for i in range(0, k + 1)) / 2 ** n
    return upper, min(1.0, 2 * min(upper, lower))


def summarise(data: dict) -> str:
    lines = HEADER + ["| first seed | seeds | abort | hold | abort share | abort > hold |", "|---|---|---|---|---|---|"]
    pooled_a = pooled_h = agree = fresh = 0
    for b in data["blocks"]:
        a = sum(r[1] for r in b["per_seed"])
        h = sum(r[2] for r in b["per_seed"])
        share = f"{a / (a + h):.3f}" if a + h else "-"
        label = f"{b['first_seed']} (the test's own)" if b["first_seed"] == IN_SUITE else str(b["first_seed"])
        lines.append(f"| {label} | {b['n']} | {a} | {h} | {share} | {'yes' if a > h else 'no'} |")
        if b["first_seed"] != IN_SUITE:
            pooled_a, pooled_h, fresh, agree = pooled_a + a, pooled_h + h, fresh + 1, agree + (a > h)
    one, two = binomial_p(pooled_a, pooled_a + pooled_h)
    lines += ["", f"Pooled over the {fresh} fresh blocks: {pooled_a} abort, {pooled_h} hold "
              f"(abort share {pooled_a / max(1, pooled_a + pooled_h):.3f}); abort exceeds hold in {agree} of {fresh} "
              f"blocks. Binomial p, abort above hold: {one:.4f}; two-sided: {two:.4f}."]
    return "\n".join(lines)


if __name__ == "__main__":
    mode = sys.argv[1]
    if mode == "run":
        run(sys.argv[2], int(sys.argv[3]), int(sys.argv[4]), int(sys.argv[5]), sys.argv[6])
    elif mode == "extract":
        print(json.dumps(extract(sys.argv[2])))
    elif mode == "summarise":
        print(summarise(json.loads(Path(sys.argv[2]).read_text())))
