"""The experiment's report, generated from the runs' summaries.

Purpose: render ``docs/llm_agent_experiment_report.md``: the model's framing block, "N of M complete" for each arm,
         each pattern's and readout's direction against A0 with the number of seeds in which it holds, and the
         contamination tests of §3.4, with no absolute threshold anywhere (LX.16, LX.20).
Spec:    docs/plan_v3_llm_agent_experiment.md#6, #3.4
Tests:   tests/experiments/llm_agents/test_report.py::test_lx16_report_is_current,
         tests/experiments/llm_agents/test_report.py::test_lx16_framing_and_counts,
         tests/experiments/llm_agents/test_report.py::test_lx20_framing_block_present
"""

from __future__ import annotations

import json
import statistics
from collections import defaultdict
from pathlib import Path

from experiments.llm_agents import files
from experiments.llm_agents.arms import ARMS
from experiments.llm_agents.config import CONFIG, LLMConfig, _table, load_llm
from src.bowen.render.trace import FRAMING

HEADER = ("<!-- Generated by experiments/llm_agents/report.py from experiments/llm_agents/runs/*/summary.json; "
          "do not edit. Regenerate: python3 -m experiments.llm_agents.runner report -->")
TEXT_KEYS = ("how", "differences", "method", "no_runs", "no_pair", "label_following", "feedback_removed",
             "opaque_plain")


def load_report_text(path: Path = CONFIG / "report_text.md") -> dict:
    text = {r["key"]: r["text"] for r in _table(path, ("key", "text"))}
    if set(text) != set(TEXT_KEYS):
        raise ValueError(f"{path}: keys {sorted(text)}, expected {sorted(TEXT_KEYS)}")
    return text


def planned(cfg: LLMConfig) -> dict[str, set]:
    """Each arm's planned runs, (phase, seed), from the phases that make results (not the smoke call or pilot)."""
    out = defaultdict(set)
    for name in ("baseline", "main", "cross_check"):
        p = cfg.phases[name]
        for arm in p.arms:
            out[arm] |= {(name, s) for s in p.seeds}
    return out


def load_summaries(runs: Path = files.RUNS) -> list[dict]:
    out = []
    for path in sorted(runs.glob("*/summary.json")):
        s = json.loads(path.read_text(encoding="utf-8"))
        rec = json.loads((path.parent / "run.json").read_text(encoding="utf-8"))
        if rec["status"] == "complete":
            s["phase"] = rec["phase"]
            out.append(s)
    return out


def _fmt(x: float) -> str:
    return f"{x:.3f}"


def _spread(values: list[float]) -> str:
    if not values:
        return "—"
    return f"{_fmt(statistics.fmean(values))} ({_fmt(min(values))}–{_fmt(max(values))})"


def _direction(xs: dict, base: dict) -> str:
    seeds = sorted(set(xs) & set(base))
    if not seeds:
        return "—"
    up = sum(1 for s in seeds if xs[s] > base[s])
    down = sum(1 for s in seeds if xs[s] < base[s])
    return f"higher in {up}, lower in {down}, equal in {len(seeds) - up - down} of {len(seeds)}"


def _ranks(values: list[float]) -> list[float]:
    order = sorted(range(len(values)), key=lambda i: values[i])
    ranks = [0.0] * len(values)
    i = 0
    while i < len(order):
        j = i
        while j + 1 < len(order) and values[order[j + 1]] == values[order[i]]:
            j += 1
        for k in range(i, j + 1):
            ranks[order[k]] = (i + j) / 2 + 1
        i = j + 1
    return ranks


def spearman(a: dict, b: dict) -> float | None:
    """Rank correlation of two frequency tables over the union of their keys (ties averaged)."""
    keys = sorted(set(a) | set(b))
    if len(keys) < 2:
        return None
    ra, rb = _ranks([a.get(k, 0) for k in keys]), _ranks([b.get(k, 0) for k in keys])
    ma, mb = statistics.fmean(ra), statistics.fmean(rb)
    num = sum((x - ma) * (y - mb) for x, y in zip(ra, rb))
    den = (sum((x - ma) ** 2 for x in ra) * sum((y - mb) ** 2 for y in rb)) ** 0.5
    return num / den if den else None


def _share(s: dict, pattern: str) -> float:
    p = s["patterns"]
    total = p["subjects"] * p["weeks"]
    return p["subject_weeks"].get(pattern, 0) / total if total else 0.0


def render(summaries: list[dict], cfg: LLMConfig | None = None, text: dict | None = None) -> str:
    """Purpose: the report's text, from the complete runs' summaries only.
    Spec:    docs/plan_v3_llm_agent_experiment.md#6
    Tests:   tests/experiments/llm_agents/test_report.py::test_lx16_framing_and_counts
    """
    cfg, text = cfg or load_llm(), text or load_report_text()
    main = [s for s in summaries if s["phase"] in ("baseline", "main")]
    by_arm = defaultdict(dict)
    for s in main:
        by_arm[s["arm"]][s["seed"]] = s
    plan = planned(cfg)
    lines = [HEADER, "", "# LLM-agent experiment — report", "", FRAMING.format(how=text["how"]), "",
             text["differences"], "", text["method"], "", "## Runs", "",
             "| Arm | Complete runs |", "|---|---|"]
    for arm in ARMS:
        done = {(s["phase"], s["seed"]) for s in summaries if s["arm"] == arm}
        lines.append(f"| {arm} | {len(done & plan[arm])} of {len(plan[arm])} complete |")
    patterns = sorted({p for s in main for p in s["patterns"]["subject_weeks"]})
    lines += ["", "## Patterns (share of subject-weeks holding each; mean and range over seeds)", ""]
    if not main:
        lines.append(text["no_runs"])
    else:
        lines += ["| Pattern | " + " | ".join(ARMS) + " |", "|---|" + "---|" * len(ARMS)]
        for pat in patterns:
            cells = []
            for arm in ARMS:
                runs = by_arm.get(arm, {})
                if not runs:
                    cells.append("—")
                    continue
                seen = sum(1 for s in runs.values() if s["patterns"]["subject_weeks"].get(pat, 0))
                cells.append(f"{_spread([_share(s, pat) for s in runs.values()])}; in {seen} of {len(runs)} seeds")
            lines.append(f"| {pat} | " + " | ".join(cells) + " |")
        lines += ["", "### Direction against A0, by seed", "",
                  "| Pattern or readout | " + " | ".join(ARMS[1:]) + " |", "|---|" + "---|" * (len(ARMS) - 1)]
        base = by_arm.get("A0", {})
        rows = [(pat, lambda s, pat=pat: _share(s, pat)) for pat in patterns]
        rows += [(k, lambda s, k=k: s["evaluation"][k]) for k in cfg.listed("evaluation_readouts")]
        for name, get in rows:
            b = {seed: get(s) for seed, s in base.items()}
            cells = [_direction({seed: get(s) for seed, s in by_arm.get(arm, {}).items()}, b) for arm in ARMS[1:]]
            lines.append(f"| {name} | " + " | ".join(cells) + " |")
        lines += ["", "### Evaluation readouts (mean and range over seeds)", "",
                  "| Readout | " + " | ".join(ARMS) + " |", "|---|" + "---|" * len(ARMS)]
        for k in cfg.listed("evaluation_readouts"):
            cells = [_spread([s["evaluation"][k] for s in by_arm.get(arm, {}).values()]) for arm in ARMS]
            lines.append(f"| {k} | " + " | ".join(cells) + " |")
    lines += ["", "## Contamination tests (§3.4)", "", "### Label-following (A3 against A2)", ""]
    a2, a3, a4, a1, a0 = (by_arm.get(a, {}) for a in ("A2", "A3", "A4", "A1", "A0"))
    seeds = sorted(set(a2) & set(a3))
    if seeds:
        more = sum(1 for s in seeds
                   if (spearman(a3[s]["acts_by_label"], a2[s]["acts_by_label"]) or 0)
                   > (spearman(a3[s]["acts_by_mechanics"], a2[s]["acts_by_mechanics"]) or 0))
        lines.append(text["label_following"].format(more=more, n=len(seeds)))
    else:
        lines.append(text["no_pair"])
    lines += ["", "### Feedback removed (A4 against A2)", ""]
    seeds = sorted(set(a2) & set(a4) & set(a0))
    if seeds:
        lines += [text["feedback_removed"], "", "| Pattern | Same direction |", "|---|---|"]
        for pat in patterns:
            def sign(run, s, pat=pat):
                d = _share(run[s], pat) - _share(a0[s], pat)
                return (d > 0) - (d < 0)
            same = sum(1 for s in seeds if sign(a4, s) == sign(a2, s))
            lines.append(f"| {pat} | {same} of {len(seeds)} seeds |")
    else:
        lines.append(text["no_pair"])
    lines += ["", "### Opaque against plain (A1 against A2)", ""]
    if a1 and a2:
        def appears(runs):
            return {p for s in runs.values() for p, n in s["patterns"]["subject_weeks"].items() if n}
        only = sorted(appears(a2) - appears(a1))
        lines.append(text["opaque_plain"].format(patterns=", ".join(only) if only else "none"))
    else:
        lines.append(text["no_pair"])
    cross = [s for s in summaries if s["phase"] == "cross_check"]
    xc = cfg.phases["cross_check"]
    lines += ["", "## Cross-check on the second model", "",
              f"{len(cross)} of {len(xc.arms) * len(xc.seeds)} planned cross-check runs complete."]
    return "\n".join(lines) + "\n"


def write_report(runs: Path = files.RUNS, report: Path = files.REPORT) -> Path:
    return files.write_text(report, render(load_summaries(runs)), runs=runs, report=report)
