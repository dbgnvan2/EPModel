HEADER = ("<!-- Generated by experiments/llm_agents/report.py from experiments/llm_agents/runs/*/summary.json; "
          "do not edit. Regenerate: python3 -m experiments.llm_agents.runner report -->")
TEXT_KEYS = ("how", "differences", "method", "no_runs", "no_pair", "label_following", "feedback_removed",
             "opaque_plain", "position", "position_effect", "position_none", "cross_check")


def load_report_text(path: Path = CONFIG / "report_text.md") -> dict:
    text = {r["key"]: r["text"] for r in _table(path, ("key", "text"))}
    if set(text) != set(TEXT_KEYS):
        raise ValueError(f"{path}: keys {sorted(text)}, expected {sorted(TEXT_KEYS)}")
    return text


def planned(cfg: LLMConfig) -> dict[str, set]:
    """Each arm's planned runs, (phase, seed), from the phases that make results (not the smoke call or pilot)."""
    out = defaultdict(set)
    for name in ("baseline", "main", "cross_check"):
        p = cfg.phases[name]
        for arm in p.arms:
            out[arm] |= {(name, s) for s in p.seeds}
    return out


def load_summaries(runs: Path = files.RUNS) -> list[dict]:
    out = []
    for path in sorted(runs.glob("*/summary.json")):
        s = json.loads(path.read_text(encoding="utf-8"))
        rec = json.loads((path.parent / "run.json").read_text(encoding="utf-8"))
        if rec["status"] == "complete":
            s["phase"] = rec["phase"]
            s["run_id"] = rec["run_id"]
            choices = read_choices(path.parent)
            if choices is not None:
                s["choices"] = choices
            out.append(s)
    return out


def _fmt(x: float) -> str:
    return f"{x:.3f}"


def _spread(values: list[float]) -> str:
    if not values:
        return "—"
    return f"{_fmt(statistics.fmean(values))} ({_fmt(min(values))}–{_fmt(max(values))})"


def _direction(xs: dict, base: dict) -> str:
    seeds = sorted(set(xs) & set(base))
    if not seeds:
        return "—"
    up = sum(1 for s in seeds if xs[s] > base[s])
    down = sum(1 for s in seeds if xs[s] < base[s])
    return f"higher in {up}, lower in {down}, equal in {len(seeds) - up - down} of {len(seeds)}"


def _ranks(values: list[float]) -> list[float]:
    order = sorted(range(len(values)), key=lambda i: values[i])
    ranks = [0.0] * len(values)
    i = 0
    while i < len(order):
        j = i
        while j + 1 < len(order) and values[order[j + 1]] == values[order[i]]:
            j += 1
        for k in range(i, j + 1):
            ranks[order[k]] = (i + j) / 2 + 1
        i = j + 1
    return ranks


def spearman(a: dict, b: dict) -> float | None:
    """Rank correlation of two frequency tables over the union of their keys (ties averaged)."""
    keys = sorted(set(a) | set(b))
    if len(keys) < 2:
        return None
    ra, rb = _ranks([a.get(k, 0) for k in keys]), _ranks([b.get(k, 0) for k in keys])
    ma, mb = statistics.fmean(ra), statistics.fmean(rb)
    num = sum((x - ma) * (y - mb) for x, y in zip(ra, rb))
    den = (sum((x - ma) ** 2 for x in ra) * sum((y - mb) ** 2 for y in rb)) ** 0.5
    return num / den if den else None


def _share(s: dict, pattern: str) -> float:
    p = s["patterns"]
    total = p["subjects"] * p["weeks"]
    return p["subject_weeks"].get(pattern, 0) / total if total else 0.0


def position_readout(choices: list[dict]) -> dict:
    """Purpose: one run's position readout (§13.4): the share of choices at position 1 against the mean of ``1/N``;
             the chosen position as a share of the list, in tenths; the week-to-week pairs of one person that repeat
             the same id against those that repeat the same option (by mechanics); the share of holds; and, where the
             arm is opaque, the share by act token. A position effect is same-id repeats above same-option repeats
             and a position-1 share above the mean of ``1/N``: a direction, no threshold (§13.4, the owner's rule).
             Shown beside it, as context the rule does not use: the same-id pairs a position-blind choice would give
             by chance (the sum of ``1/N`` over the pairs), the share at the last position, and the flagged weeks.
    Spec:    docs/plan_v3_llm_agent_experiment.md#13.4
    Tests:   tests/experiments/llm_agents/test_report.py::test_lx26_position_and_content_choosers_differ
    """
    chosen = [c for c in choices if c["id"] is not None]
    n = len(chosen)
    first = sum(1 for c in chosen if c["id"] == "1") / n if n else 0.0
    last_share = sum(1 for c in chosen if int(c["id"]) == c["options"]) / n if n else 0.0
    inverse = statistics.fmean(1 / c["options"] for c in chosen) if n else 0.0
    tenths = [0] * 10
    for c in chosen:
        tenths[min(10, math.ceil(10 * int(c["id"]) / c["options"])) - 1] += 1
    same_id = same_option = pairs = 0
    chance = 0.0
    last: dict = {}
    for c in sorted(choices, key=lambda c: (c["person"], c["week"])):
        prev = last.get(c["person"])
        last[c["person"]] = c
        if prev is None or prev["id"] is None or c["id"] is None or c["week"] != prev["week"] + 1:
            continue
        pairs += 1
        chance += 1 / c["options"]   # a position-blind choice repeats last week's id with chance 1/N
        same_id += c["id"] == prev["id"]
        same_option += _mechanics(c) == _mechanics(prev)
    tokens = defaultdict(int)
    for c in chosen:
        if c["act_token"] is not None:
            tokens[c["act_token"]] += 1
    return {"choices": n, "flagged": len(choices) - n, "position_1": first, "last": last_share,
            "same_id_chance": chance, "mean_inverse_n": inverse,
            "tenths": [x / n if n else 0.0 for x in tenths], "pairs": pairs, "same_id": same_id,
            "same_option": same_option, "holds": sum(1 for c in chosen if c["hold"]) / n if n else 0.0,
            "tokens": {k: v / n for k, v in sorted(tokens.items(), key=lambda kv: int(kv[0][1:]))},
            "effect": same_id > same_option and first > inverse}


def _mechanics(c: dict) -> tuple:
    return c["kind"], c["target"], c["third"], c["hold"]


def _position_section(summaries: list[dict], text: dict) -> list[str]:
    runs = sorted((s for s in summaries if "choices" in s), key=lambda s: (s["arm"], s["phase"], s["seed"]))
    lines = ["", "## Option position (§13.4)", "", text["position"], ""]
    if not runs:
        return lines + [text["position_none"]]
    read = {s["run_id"]: position_readout(s["choices"]) for s in runs}
    lines += ["| Run | Choices | Flagged | Position 1 | Last | Mean 1/N | Same id | Same id by chance | Same option | "
              "Pairs | Holds | Position effect |", "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for s in runs:
        r = read[s["run_id"]]
        lines.append(f"| {s['run_id']} | {r['choices']} | {r['flagged']} | {_fmt(r['position_1'])} | "
                     f"{_fmt(r['last'])} | {_fmt(r['mean_inverse_n'])} | {r['same_id']} | {r['same_id_chance']:.1f} | "
                     f"{r['same_option']} | {r['pairs']} | {_fmt(r['holds'])} | "
                     f"{'yes' if r['effect'] else 'no'} |")
    lines += ["", "Chosen position as a share of the list, in tenths (share of choices):", "",
              "| Run | " + " | ".join(f"{i}/10" for i in range(1, 11)) + " |", "|---|" + "---|" * 10]
    for s in runs:
        lines.append(f"| {s['run_id']} | " + " | ".join(_fmt(x) for x in read[s["run_id"]]["tenths"]) + " |")
    opaque = [s for s in runs if read[s["run_id"]]["tokens"]]
    if opaque:
        keys = sorted({k for s in opaque for k in read[s["run_id"]]["tokens"]}, key=lambda k: int(k[1:]))
        lines += ["", "Share of choices by act token (opaque arm):", "",
                  "| Run | " + " | ".join(keys) + " |", "|---|" + "---|" * len(keys)]
        for s in opaque:
            t = read[s["run_id"]]["tokens"]
            lines.append(f"| {s['run_id']} | " + " | ".join(_fmt(t.get(k, 0.0)) for k in keys) + " |")
    lines.append("")
    for arm in ARMS[1:]:
        main = [s for s in runs if s["arm"] == arm and s["phase"] == "main"]
        lines.append(text["position_effect"].format(arm=arm, k=sum(read[s["run_id"]]["effect"] for s in main),
                                                    n=len(main)))
    return lines


def _sign(x: float, base: float) -> int:
    return (x > base) - (x < base)


def _cross_check_section(cross: list[dict], by_arm: dict, xc, rows: list, text: dict) -> list[str]:
    """Purpose: the cross-check's direction against A0 per pattern and readout, on the second model, and in how many
             of its seeds that direction is the same as the main phase's on the same seed (a direction, no threshold).
    Spec:    docs/plan_v3_llm_agent_experiment.md#5 (the cross-check), #6
    Tests:   tests/experiments/llm_agents/test_report.py::test_lx27_cross_check_against_main
    """
    lines = [f"{len(cross)} of {len(xc.arms) * len(xc.seeds)} planned cross-check runs complete."]
    second = defaultdict(dict)
    for s in cross:
        second[s["arm"]][s["seed"]] = s
    base = by_arm.get("A0", {})
    arms = [a for a in xc.arms if second.get(a)]
    if not arms or not base:
        return lines
    lines += ["", text["cross_check"], "",
              "| Pattern or readout | " + " | ".join(f"{a} against A0 | {a} same as main" for a in arms) + " |",
              "|---|" + "---|---|" * len(arms)]
    for name, get in rows:
        cells = []
        for arm in arms:
            xs = {seed: get(s) for seed, s in second[arm].items() if seed in base}
            b = {seed: get(base[seed]) for seed in xs}
            cells.append(_direction(xs, b))
            main = by_arm.get(arm, {})
            paired = [seed for seed in xs if seed in main]
            same = sum(1 for seed in paired if _sign(xs[seed], b[seed]) == _sign(get(main[seed]), b[seed]))
            cells.append(f"{same} of {len(paired)} seeds" if paired else "—")
        lines.append(f"| {name} | " + " | ".join(cells) + " |")
    return lines


def render(summaries: list[dict], cfg: LLMConfig | None = None, text: dict | None = None) -> str:
    """Purpose: the report's text, from the complete runs' summaries only.
    Spec:    docs/plan_v3_llm_agent_experiment.md#6
    Tests:   tests/experiments/llm_agents/test_report.py::test_lx16_framing_and_counts
    """
    cfg, text = cfg or load_llm(), text or load_report_text()
    main = [s for s in summaries if s["phase"] in ("baseline", "main")]
    by_arm = defaultdict(dict)
    for s in main:
        by_arm[s["arm"]][s["seed"]] = s
    plan = planned(cfg)
    lines = [HEADER, "", "# LLM-agent experiment — report", "", FRAMING.format(how=text["how"]), "",
             text["differences"], "", text["method"], "", "## Runs", "",
             "| Arm | Complete runs |", "|---|---|"]
    for arm in ARMS:
        done = {(s["phase"], s["seed"]) for s in summaries if s["arm"] == arm}
        lines.append(f"| {arm} | {len(done & plan[arm])} of {len(plan[arm])} complete |")
    patterns = sorted({p for s in main for p in s["patterns"]["subject_weeks"]})
    lines += ["", "## Patterns (share of subject-weeks holding each; mean and range over seeds)", ""]
    rows = [(pat, lambda s, pat=pat: _share(s, pat)) for pat in patterns]
    rows += [(k, lambda s, k=k: s["evaluation"][k]) for k in cfg.listed("evaluation_readouts")]
    if not main:
        lines.append(text["no_runs"])
    else:
        lines += ["| Pattern | " + " | ".join(ARMS) + " |", "|---|" + "---|" * len(ARMS)]
        for pat in patterns:
            cells = []
            for arm in ARMS:
                runs = by_arm.get(arm, {})
                if not runs:
                    cells.append("—")
                    continue
                seen = sum(1 for s in runs.values() if s["patterns"]["subject_weeks"].get(pat, 0))
                cells.append(f"{_spread([_share(s, pat) for s in runs.values()])}; in {seen} of {len(runs)} seeds")
            lines.append(f"| {pat} | " + " | ".join(cells) + " |")
        lines += ["", "### Direction against A0, by seed", "",
                  "| Pattern or readout | " + " | ".join(ARMS[1:]) + " |", "|---|" + "---|" * (len(ARMS) - 1)]
        base = by_arm.get("A0", {})
        for name, get in rows:
            b = {seed: get(s) for seed, s in base.items()}
            cells = [_direction({seed: get(s) for seed, s in by_arm.get(arm, {}).items()}, b) for arm in ARMS[1:]]
            lines.append(f"| {name} | " + " | ".join(cells) + " |")
        lines += ["", "### Evaluation readouts (mean and range over seeds)", "",
                  "| Readout | " + " | ".join(ARMS) + " |", "|---|" + "---|" * len(ARMS)]
        for k in cfg.listed("evaluation_readouts"):
            cells = [_spread([s["evaluation"][k] for s in by_arm.get(arm, {}).values()]) for arm in ARMS]
            lines.append(f"| {k} | " + " | ".join(cells) + " |")
    lines += ["", "## Contamination tests (§3.4)", "", "### Label-following (A3 against A2)", ""]
    a2, a3, a4, a1, a0 = (by_arm.get(a, {}) for a in ("A2", "A3", "A4", "A1", "A0"))
    seeds = sorted(set(a2) & set(a3))
    if seeds:
        more = sum(1 for s in seeds
                   if (spearman(a3[s]["acts_by_label"], a2[s]["acts_by_label"]) or 0)
                   > (spearman(a3[s]["acts_by_mechanics"], a2[s]["acts_by_mechanics"]) or 0))
        lines.append(text["label_following"].format(more=more, n=len(seeds)))
    else:
        lines.append(text["no_pair"])
    lines += ["", "### Feedback removed (A4 against A2)", ""]
    seeds = sorted(set(a2) & set(a4) & set(a0))
    if seeds:
        lines += [text["feedback_removed"], "", "| Pattern | Same direction |", "|---|---|"]
        for pat in patterns:
            def sign(run, s, pat=pat):
                d = _share(run[s], pat) - _share(a0[s], pat)
                return (d > 0) - (d < 0)
            same = sum(1 for s in seeds if sign(a4, s) == sign(a2, s))
            lines.append(f"| {pat} | {same} of {len(seeds)} seeds |")
    else:
        lines.append(text["no_pair"])
    lines += ["", "### Opaque against plain (A1 against A2)", ""]
    if a1 and a2:
        def appears(runs):
            return {p for s in runs.values() for p, n in s["patterns"]["subject_weeks"].items() if n}
        only = sorted(appears(a2) - appears(a1))
        lines.append(text["opaque_plain"].format(patterns=", ".join(only) if only else "none"))
    else:
        lines.append(text["no_pair"])
    xc = cfg.phases["cross_check"]
    lines += ["", "## Cross-check on the second model", ""]
    lines += _cross_check_section([s for s in summaries if s["phase"] == "cross_check"], by_arm, xc, rows, text)
    lines += _position_section(summaries, text)
    return "\n".join(lines) + "\n"


def write_report(runs: Path = files.RUNS, report: Path = files.REPORT) -> Path:
    return files.write_text(report, render(load_summaries(runs)), runs=runs, report=report)
